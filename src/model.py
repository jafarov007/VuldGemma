"""
VuldGemma Model — Co-Attention + LoRA + Explainability
=======================================================
Bidirectional Co-Attention architecture fully compliant with Paper Section 3.3.
Explainability heatmaps can be generated by extracting cross-attention weights.
LoRA + Gradient Checkpointing + bf16 ile 30-40 GB GPU.
"""

import torch
import torch.nn as nn
import torch.nn.functional as F
from typing import Optional, Dict, Any, Tuple
from transformers import AutoModel, AutoConfig
from peft import get_peft_model, LoraConfig, TaskType


# ============================================================
# 1) CoAttentionBlock — Bidirectional Cross-Attention
# ============================================================

class CoAttentionBlock(nn.Module):
    """
    Bidirectional Cross-Attention block (Paper Section 3.3).
    CODE stream (h_q) attends to GRAPH stream (h_kv) and vice versa.
    
    Key feature: can return attention weights for explainability heatmaps.
    This directly addresses Reviewer #2's concern about attention-based explanations.
    """

    def __init__(self, d_model: int, n_heads: int = 4, dropout: float = 0.1):
        super().__init__()
        self.d_model = d_model
        self.n_heads = n_heads

        # Multi-head cross-attention
        self.attn = nn.MultiheadAttention(
            embed_dim=d_model,
            num_heads=n_heads,
            dropout=dropout,
            batch_first=True
        )

        # Feed-Forward Network
        self.ffn = nn.Sequential(
            nn.Linear(d_model, d_model * 4),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(d_model * 4, d_model),
            nn.Dropout(dropout),
        )

        self.norm1 = nn.LayerNorm(d_model)
        self.norm2 = nn.LayerNorm(d_model)
        self.dropout = nn.Dropout(dropout)

    def forward(
        self,
        h_q: torch.Tensor,
        h_kv: torch.Tensor,
        mask_q: Optional[torch.Tensor] = None,
        mask_kv: Optional[torch.Tensor] = None,
        return_weights: bool = False,
    ) -> Tuple[torch.Tensor, Optional[torch.Tensor]]:
        """
        Args:
            h_q:  (B, L_q, D) query stream
            h_kv: (B, L_kv, D) key-value stream
            mask_q:  (B, L_q)  1=keep, 0=mask
            mask_kv: (B, L_kv) 1=keep, 0=mask
            return_weights: If True, returns attention weights for heatmaps
            
        Returns:
            out: (B, L_q, D) attended output
            attn_weights: (B, L_q, L_kv) or None — cross-attention heatmap
        """
        # Key padding mask for MHA (True = ignore)
        kp_mask = ~mask_kv.bool() if mask_kv is not None else None

        attn_out, attn_weights = self.attn(
            h_q, h_kv, h_kv,
            key_padding_mask=kp_mask,
            need_weights=return_weights,
            average_attn_weights=True  # Average over heads for cleaner heatmaps
        )

        # Residual + LayerNorm
        h = self.norm1(h_q + self.dropout(attn_out))

        # FFN + Residual + LayerNorm
        ff = self.ffn(h)
        out = self.norm2(h + self.dropout(ff))

        # Zero out padding positions
        if mask_q is not None:
            out = out * mask_q.unsqueeze(-1).float()

        return out, attn_weights


# ============================================================
# 2) AttentionPooling — Single-Query Pooling
# ============================================================

class AttentionPooling(nn.Module):
    """Single-query attention pooling to compress sequence to fixed vector."""
    
    def __init__(self, d_model: int, tau: float = 1.0, dropout: float = 0.1):
        super().__init__()
        self.d_model = d_model
        self.register_buffer("_tau", torch.tensor(max(1e-3, float(tau)), dtype=torch.float32))
        self.query = nn.Parameter(torch.randn(1, d_model) * (1.0 / (d_model ** 0.5)))
        self.attn_drop = nn.Dropout(dropout)

    def forward(self, h: torch.Tensor, mask: Optional[torch.Tensor] = None) -> torch.Tensor:
        """
        Args:
            h: (B, L, D) sequence representations
            mask: (B, L) 1=keep, 0=mask
        Returns:
            pooled: (B, D) single vector summary
        """
        scores = torch.einsum("bld,hd->bhl", h, self.query) / self._tau
        if mask is not None:
            m = (mask > 0).unsqueeze(1)
            scores = scores.masked_fill(~m, float("-inf"))
        attn = torch.softmax(scores, dim=-1)
        attn = self.attn_drop(attn)
        pooled = torch.einsum("bhl,bld->bhd", attn, h)
        return pooled.squeeze(1)


# ============================================================
# 3) FusionBlock — CODE + GRAPH Embedding Fusion
# ============================================================

class FusionBlock(nn.Module):
    """Fuses CODE and GRAPH pooled embeddings with residual connection."""
    
    def __init__(self, d_model: int, dropout: float = 0.1):
        super().__init__()
        self.norm = nn.LayerNorm(d_model)
        self.skip_proj = nn.Linear(d_model * 2, d_model)
        self.fuse = nn.Sequential(
            nn.Linear(d_model * 2, d_model),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(d_model, d_model),
            nn.Dropout(dropout),
        )

    def forward(self, hc: torch.Tensor, hg: torch.Tensor) -> torch.Tensor:
        cat = torch.cat([hc, hg], dim=-1)
        skip = self.skip_proj(cat)
        z = self.fuse(cat)
        return self.norm(z + skip)


# ============================================================
# 4) ClassifierHead — Binary Vulnerability Classification
# ============================================================

class ClassifierHead(nn.Module):
    """Classification head: fused embedding -> logits."""
    
    def __init__(self, d_in: int, num_classes: int = 2, dropout: float = 0.1):
        super().__init__()
        self.fc = nn.Sequential(
            nn.Linear(d_in, d_in),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.LayerNorm(d_in),
            nn.Linear(d_in, num_classes)
        )

    def forward(self, z: torch.Tensor) -> torch.Tensor:
        return self.fc(z)


# ============================================================
# 5) VuldGemmaModel — Full Architecture
# ============================================================

class VuldGemmaModel(nn.Module):
    """
    VuldGemma: Explainable Multi-Modal Vulnerability Detection.
    
    Architecture (Paper Section 3.3):
        Gemma Encoder (shared, LoRA) 
        → Bidirectional Co-Attention (CODE↔GRAPH)
        → Attention Pooling (per stream)
        → Fusion Block
        → Classifier Head
    
    Features:
        - LoRA (PEFT): Only ~5M trainable params on 1B model → 30-40 GB GPU
        - Gradient Checkpointing: Further memory savings
        - bfloat16: Native Gemma precision
        - Cross-Attention Weights: Extractable for explainability heatmaps
        - Ablation Support: code_only / graph_only / full modes
    """

    def __init__(self, cfg: Dict[str, Any]):
        super().__init__()
        model_cfg = cfg.get("model", {})
        lora_cfg = cfg.get("lora", {})
        coattn_cfg = cfg.get("co_attention", {})

        self.model_name = model_cfg.get("base", "google/gemma-1.1-1b-it")
        self.dropout = model_cfg.get("dropout", 0.1)
        self.num_classes = model_cfg.get("num_classes", 2)

        # ── 1. Base Encoder ──
        enc_config = AutoConfig.from_pretrained(self.model_name, trust_remote_code=True)
        base_model = AutoModel.from_pretrained(
            self.model_name,
            config=enc_config,
            torch_dtype=torch.bfloat16,
            trust_remote_code=True
        )

        if hasattr(base_model.config, "use_cache"):
            base_model.config.use_cache = False
            
        use_grad_ckpt = model_cfg.get("gradient_checkpointing", True)
        if use_grad_ckpt and hasattr(base_model, "gradient_checkpointing_enable"):
            base_model.gradient_checkpointing_enable()

        self.d_model = base_model.config.hidden_size

        # ── 2. Apply LoRA ──
        if lora_cfg.get("enabled", True):
            peft_config = LoraConfig(
                task_type=TaskType.FEATURE_EXTRACTION,
                inference_mode=False,
                r=lora_cfg.get("r", 16),
                lora_alpha=lora_cfg.get("lora_alpha", 32),
                lora_dropout=lora_cfg.get("lora_dropout", 0.1),
                target_modules=lora_cfg.get("target_modules", [
                    "q_proj", "k_proj", "v_proj", "o_proj",
                    "gate_proj", "up_proj", "down_proj"
                ]),
            )
            self.encoder = get_peft_model(base_model, peft_config)
            self.encoder.print_trainable_parameters()
        else:
            self.encoder = base_model

        # ── 3. Bidirectional Co-Attention (Paper Section 3.3) ──
        co_heads = coattn_cfg.get("n_heads", 4)
        self.co_c2g = CoAttentionBlock(
            d_model=self.d_model, n_heads=co_heads, dropout=self.dropout
        )
        self.co_g2c = CoAttentionBlock(
            d_model=self.d_model, n_heads=co_heads, dropout=self.dropout
        )

        # ── 4. Attention Pooling ──
        self.pool_code = AttentionPooling(d_model=self.d_model, dropout=self.dropout)
        self.pool_graph = AttentionPooling(d_model=self.d_model, dropout=self.dropout)

        # ── 5. Fusion & Classifier ──
        self.fusion = FusionBlock(d_model=self.d_model, dropout=self.dropout)
        self.classifier = ClassifierHead(
            d_in=self.d_model, num_classes=self.num_classes, dropout=self.dropout
        )

    # ────────────────────────────────────────────────
    def encode_stream(self, input_ids: torch.Tensor, attention_mask: torch.Tensor) -> torch.Tensor:
        """Encode a single stream (CODE or GRAPH) through Gemma."""
        outputs = self.encoder(
            input_ids=input_ids, attention_mask=attention_mask, return_dict=True
        )
        return outputs.last_hidden_state

    # ────────────────────────────────────────────────
    def forward(
        self,
        code_input_ids: torch.Tensor,
        code_attention_mask: torch.Tensor,
        graph_input_ids: torch.Tensor,
        graph_attention_mask: torch.Tensor,
        return_attention: bool = False,
        mode: str = "full",  # "full" | "code_only" | "graph_only" (for ablation)
    ) -> Dict[str, torch.Tensor]:
        """
        Full forward pass.
        
        Args:
            code_input_ids, code_attention_mask: CODE stream tokens
            graph_input_ids, graph_attention_mask: GRAPH stream tokens
            return_attention: If True, returns co-attention weights for heatmaps
            mode: "full" (default), "code_only", "graph_only" for ablation studies
            
        Returns:
            dict with keys:
                "logits": (B, num_classes)
                "attn_c2g": (B, Lc, Lg) — CODE→GRAPH attention (if return_attention)
                "attn_g2c": (B, Lg, Lc) — GRAPH→CODE attention (if return_attention)
        """
        result = {}

        # ── Encode streams ──
        h_code = self.encode_stream(code_input_ids, code_attention_mask)
        
        if mode == "code_only":
            # Ablation: only code, skip graph entirely
            hc = self.pool_code(h_code, mask=code_attention_mask)
            # Use zero vector for graph
            hg = torch.zeros_like(hc)
            fused = self.fusion(hc, hg)
            result["logits"] = self.classifier(fused)
            return result

        h_graph = self.encode_stream(graph_input_ids, graph_attention_mask)
        
        if mode == "graph_only":
            # Ablation: only graph, skip code
            hg = self.pool_graph(h_graph, mask=graph_attention_mask)
            hc = torch.zeros_like(hg)
            fused = self.fusion(hc, hg)
            result["logits"] = self.classifier(fused)
            return result

        # ── Bidirectional Co-Attention ──
        h_code_aligned, attn_c2g = self.co_c2g(
            h_q=h_code, h_kv=h_graph,
            mask_q=code_attention_mask, mask_kv=graph_attention_mask,
            return_weights=return_attention
        )
        h_graph_aligned, attn_g2c = self.co_g2c(
            h_q=h_graph, h_kv=h_code,
            mask_q=graph_attention_mask, mask_kv=code_attention_mask,
            return_weights=return_attention
        )

        # ── Pooling ──
        hc = self.pool_code(h_code_aligned, mask=code_attention_mask)
        hg = self.pool_graph(h_graph_aligned, mask=graph_attention_mask)

        # ── Fusion & Classification ──
        fused = self.fusion(hc, hg)
        result["logits"] = self.classifier(fused)

        # ── Explainability: return cross-attention weights ──
        if return_attention:
            if attn_c2g is not None:
                result["attn_c2g"] = attn_c2g  # (B, Lc, Lg)
            if attn_g2c is not None:
                result["attn_g2c"] = attn_g2c  # (B, Lg, Lc)

        return result
